#!/usr/bin/env node
/**
 * The Sheets build: writes two files from the extension's library.
 *
 *   js/round_dynamic.js                  the Sheets library, the one file a
 *                                        user pastes into Apps Script
 *   claude-code-plugin/hooks/library.js  the plugin library, the one file the
 *                                        Claude Code plugin imports
 *
 * Apps Script takes the library as one pasted file, and the rounding code,
 * the number reader, the classification ladder, and the table step live
 * once, in the extension's library. For the Sheets library this script
 * joins, in order, the license header, the shared library files in
 * LIBRARY_FILES, and the Sheets entry source. For the plugin library it
 * joins the same shared library files, the extension's settings contract,
 * and one export line. LIBRARY_FILES is the one list of shared files both
 * hold.
 *
 * Usage, from any directory:
 *   node scripts/build-sheets.js          write both files and print each path
 *   node scripts/build-sheets.js --check  exit 1 when either file differs from the build
 *
 * Every path below is relative to the repository root, which is the parent
 * of this script's directory. Exits 1 when a source file is missing, and
 * writes neither file then.
 * Node standard library only.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const HEADER = 'js/src/header.js';
const ENTRY = 'js/src/entry.js';
const SETTINGS_CONTRACT = 'chrome-extension/constants.js';
// In load order: each file reads, as it loads, only names the files above
// it declare.
const LIBRARY_FILES = [
  'chrome-extension/lib/dr-number/rounding.js',
  'chrome-extension/lib/dr-number/reader.js',
  'chrome-extension/lib/dr-number/settings.js',
  'chrome-extension/lib/dr-number/numbers-in-text.js',
  'chrome-extension/lib/dr-number/dates.js',
  'chrome-extension/lib/dr-number/write-back.js',
  'chrome-extension/lib/dr-number/identifiers.js',
  'chrome-extension/lib/dr-simplify/ladder.js',
  'chrome-extension/lib/dr-simplify/table.js',
];
const BUILD_COMMAND = 'node scripts/build-sheets.js';

function notice(sources) {
  return [
    '// Generated by the Sheets build: do not edit this file. Edit its sources,',
    '// ' + sources.join(', ') + ',',
    '// then run `' + BUILD_COMMAND + '`.',
  ].join('\n') + '\n';
}

function readSource(name) {
  const file = path.join(ROOT, name);
  if (!fs.existsSync(file)) {
    fail(name + ': missing');
  }
  // One trailing newline per part, so the joined file never depends on how
  // a source file ends.
  return fs.readFileSync(file, 'utf8').replace(/\n*$/, '\n');
}

function section(name) {
  return '// ---- ' + name + ' ----\n\n' + readSource(name);
}

function buildSheetsLibrary() {
  return [
    readSource(HEADER) + notice([HEADER, ...LIBRARY_FILES, ENTRY]),
    ...LIBRARY_FILES.map(section),
    section(ENTRY),
  ].join('\n');
}

// The engine loads ES modules only, and an installed plugin is a copy of its
// own folder, so the plugin cannot import the shared files where they sit.
// The extension loads those files as content scripts, which cannot hold an
// export line, so the build adds it here.
function buildPluginLibrary() {
  const sources = [...LIBRARY_FILES, SETTINGS_CONTRACT];
  return [
    notice(sources),
    ...sources.map(section),
    'export { classifyCell, tablePatches, applyPatches, DR_DEFAULTS };\n',
  ].join('\n');
}

const OUTPUTS = [
  { file: 'js/round_dynamic.js', build: buildSheetsLibrary },
  { file: 'claude-code-plugin/hooks/library.js', build: buildPluginLibrary },
];

function fail(message) {
  process.stderr.write(message + '\n');
  process.exit(1);
}

function main(args) {
  // Every file builds before any is written, so a missing source leaves both
  // as they were.
  const outputs = OUTPUTS.map(({ file, build }) => ({ file, built: build() }));

  if (args.length === 0) {
    for (const { file, built } of outputs) {
      const outputFile = path.join(ROOT, file);
      fs.mkdirSync(path.dirname(outputFile), { recursive: true });
      fs.writeFileSync(outputFile, built);
      process.stdout.write(file + '\n');
    }
    return;
  }

  if (args.length === 1 && args[0] === '--check') {
    for (const { file, built } of outputs) {
      const outputFile = path.join(ROOT, file);
      const committed = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : null;
      if (committed !== built) {
        fail(file + ' differs from the build of its sources. Run `'
          + BUILD_COMMAND + '` and commit the result.');
      }
    }
    return;
  }

  fail('usage: ' + BUILD_COMMAND + ' [--check]');
}

main(process.argv.slice(2));
