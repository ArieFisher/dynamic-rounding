#!/usr/bin/env node
/**
 * The Sheets build: writes js/round_dynamic.js, the one file a user pastes
 * into Apps Script, from its sources.
 *
 * Apps Script takes the library as one pasted file, and the rounding code,
 * the number reader, the classification ladder, and the table step live
 * once, in the extension's library. This script joins, in order,
 * the license header, the shared library files in LIBRARY_FILES, and the
 * Sheets entry source. LIBRARY_FILES is the one list of shared files the
 * Sheets library holds.
 *
 * Usage, from any directory:
 *   node scripts/build-sheets.js          write js/round_dynamic.js and print its path
 *   node scripts/build-sheets.js --check  exit 1 when js/round_dynamic.js differs from the build
 *
 * Every path below is relative to the repository root, which is the parent
 * of this script's directory. Exits 1 when a source file is missing.
 * Node standard library only.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUTPUT = 'js/round_dynamic.js';
const HEADER = 'js/src/header.js';
const ENTRY = 'js/src/entry.js';
// In load order: each file reads, as it loads, only names the files above
// it declare.
const LIBRARY_FILES = [
  'chrome-extension/lib/dr-number/rounding.js',
  'chrome-extension/lib/dr-number/core.js',
  'chrome-extension/lib/dr-number/parsing.js',
  'chrome-extension/lib/dr-number/identifiers.js',
  'chrome-extension/lib/dr-simplify/ladder.js',
  'chrome-extension/lib/dr-simplify/table.js',
];
const BUILD_COMMAND = 'node scripts/build-sheets.js';

const NOTICE = [
  '// Generated by the Sheets build: do not edit this file. Edit its sources,',
  '// ' + [HEADER, ...LIBRARY_FILES, ENTRY].join(', ') + ',',
  '// then run `' + BUILD_COMMAND + '`.',
].join('\n') + '\n';

function readSource(name) {
  const file = path.join(ROOT, name);
  if (!fs.existsSync(file)) {
    fail(name + ': missing');
  }
  // One trailing newline per part, so the joined file never depends on how
  // a source file ends.
  return fs.readFileSync(file, 'utf8').replace(/\n*$/, '\n');
}

function section(name) {
  return '// ---- ' + name + ' ----\n\n' + readSource(name);
}

function build() {
  return [
    readSource(HEADER) + NOTICE,
    ...LIBRARY_FILES.map(section),
    section(ENTRY),
  ].join('\n');
}

function fail(message) {
  process.stderr.write(message + '\n');
  process.exit(1);
}

function main(args) {
  const outputFile = path.join(ROOT, OUTPUT);
  const built = build();

  if (args.length === 0) {
    fs.writeFileSync(outputFile, built);
    process.stdout.write(OUTPUT + '\n');
    return;
  }

  if (args.length === 1 && args[0] === '--check') {
    const committed = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : null;
    if (committed !== built) {
      fail(OUTPUT + ' differs from the build of its sources. Run `'
        + BUILD_COMMAND + '` and commit the result.');
    }
    return;
  }

  fail('usage: ' + BUILD_COMMAND + ' [--check]');
}

main(process.argv.slice(2));
